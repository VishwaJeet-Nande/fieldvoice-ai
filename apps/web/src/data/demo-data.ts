export interface FieldRep {
  id: string
  name: string
  initials: string
  role: 'field-rep' | 'manager'
  territory: string
  city: string
  status: 'online' | 'offline' | 'on-visit'
  customersAssigned: number
  visitsToday: number
  visitsCompleted: number
  avatar?: string
}

export interface Competitor {
  id: string
  name: string
  category: string
  mentions: number
  sentiment: 'positive' | 'neutral' | 'negative'
  threatLevel: 'low' | 'medium' | 'high'
  affectedCustomers: number
}

export interface PipelineOpportunity {
  id: string
  customerId: string
  customerName: string
  title: string
  value: number
  stage: 'qualified' | 'proposal' | 'negotiation' | 'verbal-commitment'
  probability: number
  ownerId: string
  ownerName: string
  expectedCloseDate: string
}

export interface ActivityItem {
  id: string
  type: 'visit' | 'voice' | 'alert' | 'action'
  title: string
  description: string
  person: string
  customerName?: string
  createdAt: string
  severity?: 'info' | 'warning' | 'high' | 'critical'
}

